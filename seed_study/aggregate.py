"""
All seeds, no exclusions: seed_study/results/*.json -> seed_study/RESULTS.md tables.

Every number is a mean over EVERY seed of a group. The "best of N by VAL" row
is printed next to it only to show how far apart the two are; it is a maximum
over GA noise, not an estimate of the method.

    python seed_study/aggregate.py
"""
import glob
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'results')


def _stats(xs):
    a = np.asarray(xs, dtype=np.float64)
    if not len(a):
        return None
    sd = float(a.std(ddof=1)) if len(a) > 1 else 0.0
    # 95 % CI of the mean, t-quantile for small n.
    t = {2: 12.71, 3: 4.30, 4: 3.18, 5: 2.78, 6: 2.57, 7: 2.45, 8: 2.36,
         9: 2.31, 10: 2.26, 11: 2.23, 12: 2.20, 13: 2.18, 14: 2.16, 15: 2.14}
    ci = t.get(len(a), 2.0) * sd / np.sqrt(len(a)) if len(a) > 1 else 0.0
    return {'n': len(a), 'mean': float(a.mean()), 'std': sd, 'ci95': ci,
            'median': float(np.median(a)), 'min': float(a.min()),
            'max': float(a.max())}


def load_group(sub, key_test, key_val):
    rows = []
    for p in sorted(glob.glob(os.path.join(RES, sub, 'seed_*.json'))):
        d = json.load(open(p, encoding='utf-8'))
        rows.append({'seed': d['ga_seed'], 'val': d.get(key_val),
                     'test': d[key_test], 'test_std': d['test_std'],
                     'size': d['size'], 'src': 'new'})
    return rows


def load_legacy(run, key_test):
    p = os.path.join(RES, 'legacy', run, 'rescored.json')
    if not os.path.exists(p):
        return []
    out = []
    for d in json.load(open(p, encoding='utf-8')):
        seed = d.get('ga_seed')
        if seed is None:
            seed = (d.get('params') or {}).get('seed', d['file'])
        out.append({'seed': seed, 'val': d.get('val_lines'),
                    'test': d[key_test], 'test_std': d['test_std'],
                    'size': d['size'], 'src': run})
    return out


def table(rows, unit, ceiling, title):
    lines = [f'#### {title}', '',
             f'| seed | source | VAL | TEST ({unit}, 30 games) | % of ceiling | nodes |',
             '|---|---|---|---|---|---|']
    for r in sorted(rows, key=lambda r: (r['src'] != 'new', str(r['seed']))):
        val = '—' if r['val'] is None else f"{r['val']:.1f}"
        lines.append(f"| {r['seed']} | {r['src']} | {val} | "
                     f"{r['test']:.1f} ± {r['test_std']:.1f} | "
                     f"{100 * r['test'] / ceiling:.0f} % | {r['size']} |")
    s = _stats([r['test'] for r in rows])
    if s:
        lines += ['', f"**All {s['n']} seeds:** {s['mean']:.1f} ± {s['std']:.1f} "
                  f"(95 % CI ± {s['ci95']:.1f}), median {s['median']:.1f}, "
                  f"min {s['min']:.1f}, max {s['max']:.1f}; "
                  f"nodes {np.mean([r['size'] for r in rows]):.0f} on average."]
        with_val = [r for r in rows if r['val'] is not None]
        if with_val:
            best = max(with_val, key=lambda r: r['val'])
            lines.append(f"Best by VAL (seed {best['seed']}): TEST {best['test']:.1f}"
                         " — shown for contrast only, not the method's number.")
        bad = [r for r in rows if r['test'] < 0.8 * ceiling]
        lines.append(f"Seeds below 80 % of the ceiling: {len(bad)} of {len(rows)}.")
    return '\n'.join(lines) + '\n', s


def main():
    out, summary = [], {}
    groups = [
        ('tetris', 'Tetris, oracle of 2026-08-20, dataset of the 2026-08-20 batch',
         load_legacy('tetris_2026-08-20_batch', 'test_lines')
         + load_group('tetris_o0820', 'test_lines', 'val_lines'), 'lines', 120.0),
        ('tetris_0712', 'Tetris, 2026-07-12 batch (old seed scheme: seed and '
         'hyper-parameters jittered together; historical)',
         load_legacy('tetris_2026-07-12_batch', 'test_lines'), 'lines', 120.0),
        ('flappy', 'Flappy Bird, fixed oracle best_ga.pt, penalty medium',
         load_group('flappy_bestga', 'test_score', 'val_score'), 'pipes', 55.0),
        ('flappy_legacy', 'Flappy Bird, benchmark.py runs of 2026-05-29 and '
         '2026-08-19 (each run trains its own oracle; weak/medium/strong)',
         load_legacy('flappy', 'test_score'), 'pipes', 55.0),
    ]
    for key, title, rows, unit, ceil in groups:
        if not rows:
            continue
        t, s = table(rows, unit, ceil, title)
        out.append(t)
        summary[key] = s
    with open(os.path.join(RES, 'summary.json'), 'w', encoding='utf-8') as f:
        json.dump(summary, f, indent=2)
    text = '\n'.join(out)
    with open(os.path.join(HERE, 'TABLES.md'), 'w', encoding='utf-8') as f:
        f.write('<!-- generated by seed_study/aggregate.py -->\n\n' + text)
    print(text)


if __name__ == '__main__':
    main()
