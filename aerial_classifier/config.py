CACHE_DIR = 'cache'
CACHE_PATH = 'dataset/cache.npz'
FEATURES_CACHE_PATH = 'dataset/features.npz'

# Выбранный датасет запоминается здесь, чтобы CLI и интерфейс работали с одним
# и тем же набором классов, а не каждый со своим.
DATASET_CHOICE_PATH = 'models/dataset.json'

# Стратифицированный сплит (доли; test = остаток).
SPLIT_TRAIN = 0.70
