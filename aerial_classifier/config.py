TRAIN_LR_DECAY = 0.5        # множитель LR на плато
TRAIN_LR_PATIENCE = 8

# Аугментация (только ветка B, только на train). В исходных TF-скриптах
# аугментация была подключена в обход backbone и фактически не работала.
AUG_FLIP = True             # аэроснимок можно вертеть как угодно
AUG_ROT90 = True
AUG_BRIGHTNESS = 0.15       # +-15% яркости


# ── EML-дистилляция ──────────────────────────────────────────────────────────
#
# Классификация => НЕ одна формула, а N_CLASSES формул: f_c(признаки) -> скаляр,
# предсказание = argmax_c f_c. Это прямой аналог tetris (argmax по постановкам),
# только argmax берётся по классам.

EML_EPSILON = 1e-10         # защита от ln(0)
EML_POPULATION = 600
EML_GENERATIONS = 600
EML_ELITISM = 20
EML_MAX_DEPTH = 7
EML_PATIENCE = 120
EML_DATA_SUBSAMPLE = 4000   # подвыборка train для оценки fitness (скорость)
EML_VAR_BONUS = 0.03        # бонус к fitness за каждую уникальную переменную

# ACC-фаза — аналог GAME-фазы Тетриса. DATA-фаза учит формулы регрессией к
# логитам оракула (MSE), но нам нужен не MSE, а ACCURACY: важен только argmax.
# Поэтому вторая фаза эволюционирует весь НАБОР из 4 формул целиком, а fitness =
# реальная сбалансированная accuracy на ПОДВЫБОРКЕ TRAIN (EML_ACC_SUBSAMPLE),
# никогда не на val/test: эволюция по val — такая же подгонка, как обучение
# градиентом, после неё val перестаёт быть независимой оценкой.
# Ровно та же логика, что «формула играет сама».
EML_ACC_ENABLED = True
EML_ACC_POPULATION = 60
EML_ACC_GENERATIONS = 60
EML_ACC_ELITISM = 6
EML_ACC_PATIENCE = 15
EML_ACC_SUBSAMPLE = 3000    # подвыборка train для оценки accuracy в ACC-фазе

DEPTH_PENALTIES = {
    'weak':   0.01,
    'medium': 0.05,
    'strong': 0.15,
}
DEPTH_PENALTY_DEFAULT = 'medium'

# Вес числа узлов в штрафе DATA-фазы, в единицах глубины.
#
# Штраф только за глубину (как было в Тетрисе) раздувание НЕ сдерживает:
# глубина всё равно ограничена EML_MAX_DEPTH, а дерево глубины 7 может иметь
# и 8 узлов, и 127 — платят одинаково. Замер: при 600 поколениях формулы
# разрослись до 106 узлов и показали на test 0.5399, тогда как прогон на 40
# поколениях дал 14 узлов и 0.5504. То есть лишние узлы не помогали, а мешали.
# Здесь узел стоит EML_SIZE_PENALTY_WEIGHT единиц глубины, поэтому сотня узлов
# добавляет к штрафу столько же, сколько 5 уровней глубины.
EML_SIZE_PENALTY_WEIGHT = 0.05

# Батч-дистилляция: несколько прогонов с разными сидами/параметрами, лучший ->
# models/best_eml.json, все -> runs/<дата>_distill/.
EML_BATCH_VARIANTS = 5
EML_BATCH_SPREAD = 0.3


# ── Ветка C: ОДНА формула на все классы ──────────────────────────────────────
#
# Ветки A и B держат по формуле на класс и берут argmax. Главный дефект этой
# схемы описан в README: формулы эволюционируют независимо, масштабы у них
# разные, и без калибровки (mu_c, sd_c) побеждает не самая уместная формула, а
# та, что выдаёт числа покрупнее.
#
# Ветка C убирает дефект по построению: формула одна, её выход — одно число,
# сравнивать не с чем. Класс достаётся из числа ТАБЛИЦЕЙ ПОРОГОВ:
#
#     f(x) -> v ;  класс = labels[searchsorted(thresholds, v)]
#
# Порогов не N_CLASSES-1, а до EMLC_MAX_INTERVALS-1, и метки участков МОГУТ
# ПОВТОРЯТЬСЯ. Это принципиально: иначе классы обязаны выстроиться в линейном
# порядке на оси, а порядка между BEACH, MOTO, PEOPLE и ROADS не существует.
# Разрешив классу занимать несколько участков, мы даём тот же эффект, ради
# которого напрашивалась периодическая функция активации, но без неё: у
# синуса от выхода EML-дерева (диапазон примерно [-10, +2.2e4]) на данные
# приходятся тысячи периодов, ландшафт fitness становится разрывным, и GA по
# нему не идёт, а блуждает.
#
# Сама таблица НЕ ЗАДАЁТСЯ ЗАРАНЕЕ. Она подбирается под выход формулы на
# каждой оценке fitness — точным динамическим программированием, максимизируя
# сбалансированную accuracy. То есть формула сама решает, в каком порядке и на
# каком расстоянии расположить классы; куда именно она их расставила — это
# результат прогона, а не наше допущение.

EMLC_MAX_INTERVALS = 12     # K: сколько участков оси может занять декодер

# Разрешение сетки порогов. Порог может встать только на границу бина, поэтому
# сетка — это точность, с которой декодер вообще способен разделить классы:
# при 64 бинах и 3000 примерах в бине ~47 значений, и граница класса внутри
# бина стоит до полутора процентов recall. Во время эволюции этого достаточно
# (fitness нужен для сравнения деревьев между собой, и промах одинаков для
# всех), а итоговая таблица подбирается по сетке в разы мельче: она считается
# один раз, и терять на ней проценты незачем.
EMLC_DECODER_BINS = 64
EMLC_FINAL_BINS = 512

EMLC_INTERVAL_PENALTY = 0.004   # штраф за каждый участок сверх числа классов

# Глубина 9 против 7 в ветке A — не поблажка, а условие честного сравнения:
# там работают N_CLASSES деревьев (в замерах ветки A это 120-310 узлов на
# набор), здесь одно. При depth 7 мы мерили бы не «одна формула против
# четырёх», а «вчетверо меньше узлов».
