# use_dataset() переписывает их все разом. Значения ниже — умолчание для
# случая, когда выбор не сделан: датасет аэроснимков, лежащий рядом с проектом.
#
# Отсюда правило для всего остального кода: обращаться через `config.X`, а не
# `from config import X` — иначе модуль запомнит имена классов на момент
# импорта и после смены датасета будет считать по старым.

