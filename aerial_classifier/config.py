# ── Выбор датасета ───────────────────────────────────────────────────────────
#
# Классы = подпапки выбранной папки. Ничего не зашито: имена, их количество и
# порядок берутся из файловой системы (порядок — алфавитный, чтобы индекс
# класса не зависел от того, в каком порядке ОС отдала записи каталога).

def _cache_paths(root: str) -> tuple[str, str]:
    """
    Куда класть кэш распакованных картинок и признаков для датасета `root`.

    Рядом с датасетом, если туда можно писать: кэш весит десятки мегабайт,
    относится именно к этой папке и удаляется вместе с ней. Если папка
    недоступна на запись (диск только для чтения, сетевой ресурс), кэш уезжает
    в CACHE_DIR проекта под именем, привязанным к пути.
    """
    if os.access(root, os.W_OK):
        return (os.path.join(root, 'cache.npz'),
                os.path.join(root, 'features.npz'))

    import hashlib
    digest = hashlib.md5(os.path.abspath(root).encode('utf-8')).hexdigest()[:8]
    slug = f"{os.path.basename(os.path.abspath(root)) or 'dataset'}_{digest}"
    return (os.path.join(CACHE_DIR, slug, 'cache.npz'),
            os.path.join(CACHE_DIR, slug, 'features.npz'))


def use_dataset(root: str, class_names: list[str] | None = None) -> dict:
    """
    Переключить проект на другую папку с классами.

    class_names=None — определить по подпапкам (обычный случай). Явный список
    нужен, когда часть подпапок надо исключить.

    Меняет DATASET_DIR, CLASS_NAMES, N_CLASSES и пути кэшей. Возвращает
    словарь с тем, что получилось, — его удобно показать пользователю до того,
    как он запустит обучение на неожиданно другом наборе классов.
    """
    global DATASET_DIR, CLASS_NAMES, N_CLASSES, CACHE_PATH, FEATURES_CACHE_PATH

    root = os.path.normpath(root)
    if class_names is None:
        import data
        class_names = data.scan_classes(root)
    if not class_names:
        raise ValueError(
            f"в папке {root} нет подпапок с картинками. Ожидается структура "
            f"{root}/<ИМЯ КЛАССА>/*.bmp|png|jpg")

    DATASET_DIR = root
    CLASS_NAMES = list(class_names)
    N_CLASSES = len(CLASS_NAMES)
    CACHE_PATH, FEATURES_CACHE_PATH = _cache_paths(root)
    return {'root': DATASET_DIR, 'classes': CLASS_NAMES,
            'n_classes': N_CLASSES, 'cache': CACHE_PATH}


def save_dataset_choice() -> str:
    """Запомнить текущий выбор, чтобы CLI и интерфейс видели один датасет."""
    import json
    os.makedirs(os.path.dirname(DATASET_CHOICE_PATH) or '.', exist_ok=True)
    with open(DATASET_CHOICE_PATH, 'w', encoding='utf-8') as f:
        json.dump({'root': DATASET_DIR, 'classes': CLASS_NAMES}, f,
                  indent=2, ensure_ascii=False)
    return DATASET_CHOICE_PATH


def load_dataset_choice(verbose: bool = False) -> bool:
    """
    Применить запомненный выбор. True, если он был и его удалось применить.

    Вызывается ЯВНО из main.py и gui.py, а не при импорте config: тесты не
    должны зависеть от того, какую папку пользователь выбрал в прошлый раз.
    Пропавшая папка — не ошибка запуска: возвращаемся к умолчанию и говорим
    об этом, иначе программа перестала бы стартовать из-за отключённой флешки.
    """
    import json
    if not os.path.exists(DATASET_CHOICE_PATH):
        return False
    try:
        with open(DATASET_CHOICE_PATH, 'r', encoding='utf-8') as f:
            saved = json.load(f)
        root = saved['root']
        if not os.path.isdir(root):
            if verbose:
                print(f"[config] запомненный датасет {root} не найден — "
                      f"остаюсь на {DATASET_DIR}")
            return False
        use_dataset(root, saved.get('classes') or None)
        if verbose:
            print(f"[config] датасет: {DATASET_DIR} "
                  f"({N_CLASSES} классов: {', '.join(CLASS_NAMES)})")
        return True
    except (OSError, ValueError, KeyError) as exc:
        if verbose:
            print(f"[config] не удалось прочитать {DATASET_CHOICE_PATH}: {exc}")
        return False


def dataset_summary() -> str:
    """Однострочное описание текущего датасета — для логов и заголовков окон."""
    return f"{DATASET_DIR} — {N_CLASSES} кл.: {', '.join(CLASS_NAMES)}"
