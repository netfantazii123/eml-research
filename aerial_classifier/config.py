"""
aerial_classifier — конфигурация.
Все гиперпараметры проекта в одном месте (по образцу tetris/config.py).

Задача: классификация аэрофотоснимков 64x64 на 4 класса. Отличие от этапов 1-2
(Flappy, Tetris) — здесь нет среды и нет политики: оракул решает задачу
supervised-классификации, а EML-формулы аппроксимируют его решающую функцию.

Три фазы пайплайна — три блока констант:
  1. Данные (загрузка BMP, сплиты, признаки)
  2. Оракул (MLP на признаках / CNN на пикселях)
  3. EML-дистилляция

ТРИ ВЕТКИ (см. README):
  A (основная) — оракул ест 32 инженерных признака, EML ест ТЕ ЖЕ признаки,
                 формул N_CLASSES штук, решение = argmax.
                 На микроконтроллере не остаётся ничего от нейросети.
  B (ablation) — оракул CNN ест пиксели, EML ест его bottleneck-эмбеддинг.
                 Верхняя граница качества; свёртки на MCU остаются.
  C (эксперимент) — те же признаки, что в A, но формула ОДНА на все классы:
                 скаляр + подобранная под него таблица порогов. Снимает
                 проблему сопоставимости шкал, из-за которой ветке A нужна
                 калибровка (см. блок «Ветка C» ниже).
"""

