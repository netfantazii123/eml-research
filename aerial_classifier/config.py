"""
aerial_classifier — конфигурация.
Все гиперпараметры проекта в одном месте (по образцу tetris/config.py).

Задача: классификация аэрофотоснимков 64x64 на 4 класса. Отличие от этапов 1-2
(Flappy, Tetris) — здесь нет среды и нет политики: оракул решает задачу
supervised-классификации, а EML-формулы аппроксимируют его решающую функцию.

Три фазы пайплайна — три блока констант:
  1. Данные (загрузка BMP, сплиты, признаки)
  2. Оракул (MLP на признаках / CNN на пикселях)
  3. EML-дистилляция

ДВЕ ВЕТКИ (см. README):
  A (основная) — оракул ест 32 инженерных признака, EML ест ТЕ ЖЕ признаки.
                 На микроконтроллере не остаётся ничего от нейросети.
  B (ablation) — оракул CNN ест пиксели, EML ест его bottleneck-эмбеддинг.
                 Верхняя граница качества; свёртки на MCU остаются.
"""

# ── Данные ───────────────────────────────────────────────────────────────────

DATASET_DIR = 'dataset'
CLASS_NAMES = ['BEACH', 'MOTO', 'PEOPLE', 'ROADS']
N_CLASSES = len(CLASS_NAMES)

IMG_SIZE = 64               # все картинки датасета ровно 64x64 (проверено)
IMG_CHANNELS = 3

# Кэш распакованного датасета: BMP-файлы читаются один раз, дальше — .npz.
CACHE_PATH = 'dataset/cache.npz'
FEATURES_CACHE_PATH = 'dataset/features.npz'

# Стратифицированный сплит (доли; test = остаток).
SPLIT_TRAIN = 0.70
SPLIT_VAL = 0.15
SPLIT_SEED = 1337           # тот же сид, что в исходных TF-скриптах

# Датасет несбалансирован (ROADS 2057 : BEACH 612 = 3.4:1) — в лоссе оракула
# используются веса классов 1/freq, иначе сеть выучивает приор «всё это ROADS».
USE_CLASS_WEIGHTS = True


# ── Признаки (ветка A) ───────────────────────────────────────────────────────
#
# 32 признака, все считаются за 1-2 прохода по картинке целочисленной
# арифметикой + несколько делений => реалистично для STM32.
# Порядок ВАЖЕН: var_idx в EML-дереве индексирует именно этот список.

FEATURE_NAMES = [
    # -- Цвет: моменты каналов и оппонентных осей (14) --
    'mean_r', 'mean_g', 'mean_b',
    'std_r', 'std_g', 'std_b',
    'mean_gray', 'std_gray',
    'mean_rg', 'mean_yb',          # оппонентность (R-G) и (R+G-2B)
    'std_rg', 'std_yb',
    'mean_sat', 'std_sat',         # насыщенность (max-min)/max

    # -- Текстура и края (8) --
    'grad_x', 'grad_y',            # средние |dI/dx|, |dI/dy|
    'grad_mag', 'grad_std',
    'edge_density',                # доля пикселей с сильным градиентом
    'anisotropy',                  # (gx-gy)/(gx+gy): вытянутость текстуры
    'coherence',                   # структурный тензор: линейность (дороги!)
    'entropy',                     # энтропия гистограммы яркости

    # -- Локальная шероховатость по блокам 8x8 (2) --
    'block_std',                   # средний разброс ВНУТРИ блоков
    'block_spread',                # разброс СРЕДНИХ между блоками

    # -- Пространственная раскладка (8) --
    'center_gray_diff',            # центр 32x32 минус периферия
    'center_sat_diff',
    'center_edge_diff',            # объект в центре => краёв в центре больше
    'radial_slope',                # корреляция яркости с расстоянием от центра
    'block16_spread',              # разброс средних по блокам 16x16 (крупный масштаб)
    'quad_spread',                 # разброс яркости по 4 квадрантам
    'dark_frac', 'bright_frac',    # доли тёмных и ярких пикселей
]
N_FEATURES = len(FEATURE_NAMES)          # 32

EDGE_THRESHOLD = 24.0       # порог |grad| для edge_density (шкала 0..255)
DARK_THRESHOLD = 60.0       # порог «тёмный пиксель» (0..255)
BRIGHT_THRESHOLD = 190.0    # порог «яркий пиксель» (0..255)
ENTROPY_BINS = 16           # бинов гистограммы для entropy
BLOCK_SIZE = 8              # размер блока для block_std / block_spread


# ── Оракул ───────────────────────────────────────────────────────────────────

# Ветка A: MLP на 32 признаках.
MLP_HIDDEN = [128, 64]
MLP_DROPOUT = 0.2

# Ветка B: маленькая CNN на пикселях с узким bottleneck-эмбеддингом.
# Эмбеддинг сознательно узкий: EML-формула должна получить вектор того же
# порядка размерности, что и признаки ветки A, иначе сравнение нечестное.
CNN_CHANNELS = [32, 64, 128]
CNN_EMBED_DIM = 32          # = N_FEATURES, чтобы ветки были сопоставимы
CNN_DROPOUT = 0.3

TRAIN_EPOCHS = 120
TRAIN_BATCH_SIZE = 64
TRAIN_LR = 1e-3
TRAIN_WEIGHT_DECAY = 1e-4
TRAIN_PATIENCE = 25         # эпох без роста val accuracy -> стоп
TRAIN_LR_DECAY = 0.5        # множитель LR на плато
TRAIN_LR_PATIENCE = 8

# Аугментация (только ветка B, только на train). В исходных TF-скриптах
# аугментация была подключена в обход backbone и фактически не работала.
AUG_FLIP = True             # аэроснимок можно вертеть как угодно
AUG_ROT90 = True
AUG_BRIGHTNESS = 0.15       # +-15% яркости


# ── EML-дистилляция ──────────────────────────────────────────────────────────
#
# Классификация => НЕ одна формула, а N_CLASSES формул: f_c(признаки) -> скаляр,
# предсказание = argmax_c f_c. Это прямой аналог tetris (argmax по постановкам),
# только argmax берётся по классам.

EML_EPSILON = 1e-10         # защита от ln(0)
EML_POPULATION = 600
EML_GENERATIONS = 600
EML_ELITISM = 20
EML_MAX_DEPTH = 7
EML_PATIENCE = 120
EML_DATA_SUBSAMPLE = 4000   # подвыборка train для оценки fitness (скорость)
EML_VAR_BONUS = 0.03        # бонус к fitness за каждую уникальную переменную

# ACC-фаза — аналог GAME-фазы Тетриса. DATA-фаза учит формулы регрессией к
# логитам оракула (MSE), но нам нужен не MSE, а ACCURACY: важен только argmax.
# Поэтому вторая фаза эволюционирует весь НАБОР из 4 формул целиком, а fitness =
# реальная сбалансированная accuracy на ПОДВЫБОРКЕ TRAIN (EML_ACC_SUBSAMPLE),
# никогда не на val/test: эволюция по val — такая же подгонка, как обучение
# градиентом, после неё val перестаёт быть независимой оценкой.
# Ровно та же логика, что «формула играет сама».
EML_ACC_ENABLED = True
EML_ACC_POPULATION = 60
EML_ACC_GENERATIONS = 60
EML_ACC_ELITISM = 6
EML_ACC_PATIENCE = 15
EML_ACC_SUBSAMPLE = 3000    # подвыборка train для оценки accuracy в ACC-фазе

DEPTH_PENALTIES = {
    'weak':   0.01,
    'medium': 0.05,
    'strong': 0.15,
}
DEPTH_PENALTY_DEFAULT = 'medium'

# Вес числа узлов в штрафе DATA-фазы, в единицах глубины.
#
# Штраф только за глубину (как было в Тетрисе) раздувание НЕ сдерживает:
# глубина всё равно ограничена EML_MAX_DEPTH, а дерево глубины 7 может иметь
# и 8 узлов, и 127 — платят одинаково. Замер: при 600 поколениях формулы
# разрослись до 106 узлов и показали на test 0.5399, тогда как прогон на 40
# поколениях дал 14 узлов и 0.5504. То есть лишние узлы не помогали, а мешали.
# Здесь узел стоит EML_SIZE_PENALTY_WEIGHT единиц глубины, поэтому сотня узлов
# добавляет к штрафу столько же, сколько 5 уровней глубины.
EML_SIZE_PENALTY_WEIGHT = 0.05

# Батч-дистилляция: несколько прогонов с разными сидами/параметрами, лучший ->
# models/best_eml.json, все -> runs/<дата>_distill/.
EML_BATCH_VARIANTS = 5
EML_BATCH_SPREAD = 0.3


# ── Директории ───────────────────────────────────────────────────────────────

MODELS_DIR = 'models'
RESULTS_DIR = 'results'
LOGS_DIR = 'logs'
RUNS_DIR = 'runs'
